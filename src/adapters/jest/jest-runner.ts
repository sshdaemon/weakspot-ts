import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { Package } from '../../change/types.ts';
import type { RunOptions, RunResult, ShimOptions, TestRunner } from '../../ports/test-runner.ts';
import { hasJestKey } from '../fs/package-locator.ts';
import { ENV_MODULE, envSource, runCli, runnerBin } from '../runner-cli.ts';

/**
 * Any `jest*` file in a config format: `jest.config.ts`, `jest-e2e.config.js`, Nest's `jest-e2e.json`. The unit
 * lane's locator looks only for `jest.config.*`, so a broader name reaches here only as a lane's own config.
 */
const JEST_CONFIG = /(^|\/)jest[^/]*\.([cm]?[jt]s|json)$/;

/**
 * Jest behind the TestRunner port. The shim is an ES module that reads the package's own config with
 * the project's Jest, sets rootDir onto the new root (the engine's sandbox) and narrows the tests to
 * the given specs; see jestShimSource for how paths move.
 */
export class JestRunner implements TestRunner {
  readonly name = 'jest';

  detect(pkg: Package): boolean {
    return JEST_CONFIG.test(pkg.testConfig) || (path.basename(pkg.testConfig) === 'package.json' && hasJestKey(pkg.testConfig));
  }

  /** Jest reads `.mjs` configs, not `.mts`, so the shim takes that extension whatever `outPath` has. */
  writeShim(pkg: Package, opts: ShimOptions, outPath: string): string {
    const shimPath = `${outPath.replace(/\.[cm]?[jt]s$/, '')}.mjs`;
    mkdirSync(path.dirname(shimPath), { recursive: true });
    writeFileSync(path.join(path.dirname(shimPath), ENV_MODULE), envSource(opts.env ?? {}, opts.workerIdVariable, opts.workerOffset ?? 0));
    writeFileSync(shimPath, jestShimSource(pkg, opts));
    return shimPath;
  }

  engineConfig(_pkg: Package, shimPath: string): Record<string, unknown> {
    return { testRunner: 'jest', jest: { projectType: 'custom', configFile: shimPath, enableFindRelatedTests: false } };
  }

  /**
   * In band: the specs of one file are few, and the shim's env then reaches them without worker
   * processes. --forceExit: a spec that leaves a handle open would otherwise keep Jest alive until the time limit.
   */
  run(pkg: Package, shimPath: string, cwd: string, timeoutMs: number, opts: RunOptions = {}): Promise<RunResult> {
    const reportFile = `${shimPath.replace(/\.mjs$/, '')}-run.json`;
    const args = ['--config', shimPath, '--json', '--outputFile', reportFile, '--runInBand', '--ci', '--no-watchman', '--forceExit'];
    return runCli(runnerBin(pkg.dir, 'jest'), args, cwd, reportFile, timeoutMs, opts);
  }
}

/**
 * Source of the generated config. Exported so tests can check what it does to a config shape.
 *
 * The package's config is read with the project's own Jest (`readInitialOptions`, as Jest and Stryker's
 * plugin read it), so any config Jest loads works here. Paths it names that resolve inside the package
 * move onto the new root, so specs load the sandbox's copies; paths that resolve outside it (a preset
 * or setup file at the monorepo root) become absolute real paths, since the new root has no parent
 * folders. `globalSetup` and `globalTeardown` always stay in the real package, as with Vitest.
 */
export function jestShimSource(pkg: Package, opts: ShimOptions): string {
  const root = opts.root === 'cwd' ? 'process.cwd()' : JSON.stringify(opts.root);
  const include = opts.include === undefined ? 'undefined' : JSON.stringify(opts.include);
  return `// generated by weakspot: wraps the package's Jest config, narrows rootDir and the tests it runs
import './${ENV_MODULE}';
import { createRequire } from 'node:module';
import path from 'node:path';
const PKG = ${JSON.stringify(pkg.dir)};
const CONFIG = ${JSON.stringify(pkg.testConfig)};
const root = ${root};
const fromPkg = createRequire(PKG + '/noop.js');
const jestConfig = createRequire(createRequire(fromPkg.resolve('jest')).resolve('jest-cli'))('jest-config');
const { config: base } = await jestConfig.readInitialOptions(CONFIG, { skipMultipleConfigError: true });
const inside = (p) => p === PKG || p.startsWith(PKG + '/');
const toRoot = (p) => root + p.slice(PKG.length);
const ownRoot = path.resolve(PKG, base.rootDir ?? '.');
// A path (relative, absolute or <rootDir>-based) as Jest resolves it, from the real package; a module name stays.
const isPath = (p) => typeof p === 'string' && (p.includes('<rootDir>') || p.startsWith('.') || path.isAbsolute(p));
const real = (p) => path.resolve(ownRoot, p.split('<rootDir>').join(ownRoot));
const place = (p) => (isPath(p) ? (inside(real(p)) ? toRoot(real(p)) : real(p)) : p);
const keep = (p) => (isPath(p) ? real(p) : p);
const each = (v, f) => (Array.isArray(v) ? v.map((x) => (Array.isArray(x) ? [f(x[0]), ...x.slice(1)] : f(x))) : f(v));
const values = (o, f) => (o && typeof o === 'object' ? Object.fromEntries(Object.entries(o).map(([k, v]) => [k, each(v, f)])) : o);
const deep = (v) => (Array.isArray(v) ? v.map(deep) : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, deep(x)])) : typeof v === 'string' && inside(v) ? toRoot(v) : v);
const escape = (s) => s.replace(/[[\\]{}()*?!]/g, (c) => '[' + c + ']');
// Every option Jest resolves as a path against rootDir: a single path, a list, or [path, options] entries.
const PATHS = ['preset', 'setupFiles', 'setupFilesAfterEnv', 'testEnvironment', 'resolver', 'snapshotResolver', 'modulePaths', 'testSequencer', 'dependencyExtractor', 'prettierPath', 'snapshotSerializers', 'runner', 'testRunner', 'runtime', 'filter', 'testResultsProcessor', 'watchPlugins', 'reporters'];
const { projects, testRegex, testMatch, roots, globalSetup, globalTeardown, rootDir: _rootDir, moduleNameMapper, transform, ...rest } = base;
const cfg = deep(rest);
for (const key of PATHS) if (rest[key] !== undefined) cfg[key] = each(rest[key], place);
if (moduleNameMapper) cfg.moduleNameMapper = values(moduleNameMapper, place);
if (transform) cfg.transform = values(transform, place);
if (rest.haste?.hasteImplModulePath) cfg.haste = { ...cfg.haste, hasteImplModulePath: place(rest.haste.hasteImplModulePath) };
cfg.rootDir = inside(ownRoot) ? toRoot(ownRoot) : ownRoot;
// Jest 29 loads a file preset only by a dot-relative path from rootDir; an absolute one fails there.
if (isPath(rest.preset)) cfg.preset = './' + path.relative(cfg.rootDir, place(rest.preset));
cfg.collectCoverage = false;
cfg.watchman = false;
const include = ${include};
cfg.roots = include ? [root] : roots ? each(roots, place) : ['<rootDir>'];
// testRegex = [] too: a preset's testRegex would otherwise clash with testMatch, as presets merge first.
if (include) { cfg.testMatch = include.map((s) => escape(path.join(root, s))); cfg.testRegex = []; }
else if (testRegex) cfg.testRegex = testRegex;
else if (testMatch) cfg.testMatch = testMatch;
if (globalSetup) cfg.globalSetup = keep(globalSetup);
if (globalTeardown) cfg.globalTeardown = keep(globalTeardown);
export default cfg;
`;
}
